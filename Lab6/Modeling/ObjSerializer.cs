using System.Globalization;
using System.Text;
using Lab6.Core.Geometry;
using Lab6.Core.Mathematics;
using MathNet.Numerics.LinearAlgebra;

namespace Lab6.IO;

public static class ObjSerializer
{
    private static readonly CultureInfo Culture = CultureInfo.InvariantCulture;

    public static Polyhedron Load(string filePath)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(filePath);

        var positions = new List<Point3D>();
        var textureCoordinates = new List<TextureCoordinate>();
        var normals = new List<Normal>();
        var faces = new List<Polygon>();

        var lineNumber = 0;
        foreach (var sourceLine in File.ReadLines(filePath))
        {
            lineNumber++;
            var line = RemoveComment(sourceLine).Trim();
            if (line.Length == 0)
                continue;

            var parts = line.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
            switch (parts[0].ToLowerInvariant())
            {
                case "v":
                    positions.Add(ParsePosition(parts, lineNumber));
                    break;
                case "vt":
                    textureCoordinates.Add(ParseTextureCoordinate(parts, lineNumber));
                    break;
                case "vn":
                    normals.Add(ParseNormal(parts, lineNumber));
                    break;
                case "f":
                    faces.Add(ParseFace(parts, positions.Count, textureCoordinates.Count, normals.Count, lineNumber));
                    break;
            }
        }

        if (positions.Count == 0)
            throw Error(0, "Файл не содержит вершин v.");
        if (faces.Count == 0)
            throw Error(0, "Файл не содержит граней f.");

        ValidateFaces(faces, positions.Count, textureCoordinates.Count, normals.Count);

        var model = new Polyhedron(positions, faces, textureCoordinates, normals);
        model.RebuildEdges();
        return model;
    }

    public static void Save(string filePath, Polyhedron model, Matrix<double>? transform = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(filePath);
        ArgumentNullException.ThrowIfNull(model);
        ValidateFaces(model.Faces, model.Positions.Count, model.TextureCoordinates.Count, model.Normals.Count);

        var positions = transform is null
            ? model.Positions
            : model.Positions.Select(point => TransformMatrix.Transform(transform, point)).ToList();
        var normals = TransformNormals(model.Normals, transform);

        using var writer = new StreamWriter(filePath, false, new UTF8Encoding(false));
        writer.WriteLine("# Wavefront OBJ generated by Lab6");
        writer.WriteLine($"# vertices: {positions.Count}, faces: {model.Faces.Count}");
        writer.WriteLine($"o {ObjectName(filePath)}");

        foreach (var point in positions)
            writer.WriteLine($"v {Number(point.X)} {Number(point.Y)} {Number(point.Z)}");

        foreach (var texture in model.TextureCoordinates)
        {
            var values = new List<string> { Number(texture.U) };
            if (texture.V.HasValue)
                values.Add(Number(texture.V.Value));
            if (texture.W.HasValue)
                values.Add(Number(texture.W.Value));
            writer.WriteLine($"vt {string.Join(" ", values)}");
        }

        foreach (var normal in normals)
            writer.WriteLine($"vn {Number(normal.X)} {Number(normal.Y)} {Number(normal.Z)}");

        foreach (var face in model.Faces)
            writer.WriteLine($"f {string.Join(" ", face.Vertices.Select(FormatFaceVertex))}");
    }

    private static Point3D ParsePosition(string[] parts, int lineNumber)
    {
        Require(parts, 4, lineNumber, "Вершина v должна содержать координаты X, Y и Z.");
        var x = ParseNumber(parts[1], lineNumber);
        var y = ParseNumber(parts[2], lineNumber);
        var z = ParseNumber(parts[3], lineNumber);
        var w = parts.Length > 4 ? ParseNumber(parts[4], lineNumber) : 1d;
        if (Math.Abs(w) < 1e-12)
            throw Error(lineNumber, "Однородная координата W вершины не может быть равна нулю.");
        return new Point3D(x / w, y / w, z / w);
    }

    private static TextureCoordinate ParseTextureCoordinate(string[] parts, int lineNumber)
    {
        Require(parts, 2, lineNumber, "Текстурная координата vt должна содержать компоненту U.");
        return new TextureCoordinate(
            ParseNumber(parts[1], lineNumber),
            parts.Length > 2 ? ParseNumber(parts[2], lineNumber) : null,
            parts.Length > 3 ? ParseNumber(parts[3], lineNumber) : null);
    }

    private static Normal ParseNormal(string[] parts, int lineNumber)
    {
        Require(parts, 4, lineNumber, "Нормаль vn должна содержать координаты X, Y и Z.");
        return new Normal(
            ParseNumber(parts[1], lineNumber),
            ParseNumber(parts[2], lineNumber),
            ParseNumber(parts[3], lineNumber));
    }

    private static Polygon ParseFace(
        string[] parts, int positionCount, int textureCount, int normalCount, int lineNumber)
    {
        Require(parts, 4, lineNumber, "Грань f должна содержать минимум три вершины.");
        var vertices = new List<FaceVertex>(parts.Length - 1);
        for (var i = 1; i < parts.Length; i++)
            vertices.Add(ParseFaceVertex(parts[i], positionCount, textureCount, normalCount, lineNumber));
        return new Polygon(vertices);
    }

    private static FaceVertex ParseFaceVertex(
        string token, int positionCount, int textureCount, int normalCount, int lineNumber)
    {
        var indices = token.Split('/');
        if (indices.Length is < 1 or > 3 || indices[0].Length == 0)
            throw Error(lineNumber, $"Некорректная вершина грани: {token}.");

        var position = ParseIndex(indices[0], positionCount, "вершины", lineNumber);
        int? texture = indices.Length > 1 && indices[1].Length > 0
            ? ParseIndex(indices[1], textureCount, "текстурной координаты", lineNumber)
            : null;
        int? normal = indices.Length > 2 && indices[2].Length > 0
            ? ParseIndex(indices[2], normalCount, "нормали", lineNumber)
            : null;
        return new FaceVertex(position, texture, normal);
    }

    private static int ParseIndex(string text, int currentCount, string kind, int lineNumber)
    {
        if (!int.TryParse(text, NumberStyles.Integer, Culture, out var value) || value == 0)
            throw Error(lineNumber, $"Некорректный индекс {kind}: {text}.");

        var index = value > 0 ? value - 1 : currentCount + value;
        if (index < 0 || value < 0 && index >= currentCount)
            throw Error(lineNumber, $"Индекс {kind} {text} выходит за пределы списка.");
        return index;
    }

    private static void ValidateFaces(IEnumerable<Polygon> faces, int positionCount, int textureCount, int normalCount)
    {
        foreach (var vertex in faces.SelectMany(face => face.Vertices))
        {
            ValidateIndex(vertex.PositionIndex, positionCount, "вершины");
            if (vertex.TextureCoordinateIndex is int texture)
                ValidateIndex(texture, textureCount, "текстурной координаты");
            if (vertex.NormalIndex is int normal)
                ValidateIndex(normal, normalCount, "нормали");
        }
    }

    private static void ValidateIndex(int index, int count, string kind)
    {
        if (index < 0 || index >= count)
            throw new FormatException($"Индекс {kind} {index + 1} выходит за пределы списка.");
    }

    private static IReadOnlyList<Normal> TransformNormals(IReadOnlyList<Normal> normals, Matrix<double>? transform)
    {
        if (transform is null || normals.Count == 0)
            return normals;

        Matrix<double> normalMatrix;
        try
        {
            normalMatrix = transform.SubMatrix(0, 3, 0, 3).Inverse().Transpose();
        }
        catch (ArgumentException exception)
        {
            throw new InvalidOperationException(
                "Нельзя преобразовать нормали: матрица модели необратима.", exception);
        }

        return normals.Select(normal =>
        {
            var vector = Vector<double>.Build.DenseOfArray([normal.X, normal.Y, normal.Z]) * normalMatrix;
            var length = vector.L2Norm();
            return length < 1e-12
                ? new Normal(0, 0, 0)
                : new Normal(vector[0] / length, vector[1] / length, vector[2] / length);
        }).ToList();
    }

    private static string FormatFaceVertex(FaceVertex vertex)
    {
        var position = (vertex.PositionIndex + 1).ToString(Culture);
        var texture = vertex.TextureCoordinateIndex is int textureIndex
            ? (textureIndex + 1).ToString(Culture)
            : null;
        var normal = vertex.NormalIndex is int normalIndex
            ? (normalIndex + 1).ToString(Culture)
            : null;

        if (texture is null && normal is null)
            return position;
        if (normal is null)
            return $"{position}/{texture}";
        return $"{position}/{texture}/{normal}";
    }

    private static string RemoveComment(string line)
    {
        var comment = line.IndexOf('#');
        return comment >= 0 ? line[..comment] : line;
    }

    private static double ParseNumber(string text, int lineNumber)
    {
        if (!double.TryParse(text, NumberStyles.Float, Culture, out var value) || !double.IsFinite(value))
            throw Error(lineNumber, $"Некорректное число: {text}.");
        return value;
    }

    private static void Require(string[] parts, int count, int lineNumber, string message)
    {
        if (parts.Length < count)
            throw Error(lineNumber, message);
    }

    private static FormatException Error(int lineNumber, string message) =>  new(lineNumber > 0 ? $"Строка {lineNumber}: {message}" : message);

    private static string Number(double value) => value.ToString("G17", Culture);

    private static string ObjectName(string filePath)
    {
        var name = Path.GetFileNameWithoutExtension(filePath);
        return string.IsNullOrWhiteSpace(name) ? "model"
            : string.Concat(name.Select(character => char.IsWhiteSpace(character) ? '_' : character));
    }
}
